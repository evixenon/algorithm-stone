# [141] Linked List Cycle
#

# @lc code=start
# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, x):
#         self.val = x
#         self.next = None

class Solution:
    def hasCycle(self, head: Optional[ListNode]) -> bool:
        fast = slow = head
        while True:
            if not (fast and fast.next): return
            fast = fast.next.next
            slow = slow.next
            if fast == slow: return True
# @lc code=end

